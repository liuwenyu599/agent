#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
从现存容器反推 `docker run` 命令，落盘成 run-<容器名>.sh。

背景：生产机上的容器都是手工 docker run 起的，没有 compose 托管，
一旦容器丢失/要改参数，只能靠 docker inspect 反推（容易漏掉 bind mount，
而 bind mount 恰恰是昇腾容器能跑起来的关键，且 docker commit 不保存它）。
本脚本把每个容器的完整启动参数固化成可执行的 shell 脚本。

用法：
    python3 generate-run-scripts.py                 # 所有容器（含已停止）
    python3 generate-run-scripts.py justice-api     # 指定若干容器
    OUT_DIR=/somewhere python3 generate-run-scripts.py

产物： $OUT_DIR/run-<容器名>.sh   （chmod +x，可直接 bash 执行）
"""
import json
import os
import shlex
import subprocess
import sys

OUT_DIR = os.environ.get("OUT_DIR", "/opt/justice-office/deploy")


def sh(args):
    return subprocess.run(args, capture_output=True, text=True, check=True).stdout


def q(s):
    return shlex.quote(str(s))


def image_cfg(image):
    try:
        return json.loads(sh(["docker", "image", "inspect", image]))[0]["Config"]
    except subprocess.CalledProcessError:
        return {"Env": [], "Entrypoint": None}


def build_run(name):
    c = json.loads(sh(["docker", "inspect", name]))[0]
    cfg, hc = c["Config"], c["HostConfig"]
    img = cfg["Image"]
    icfg = image_cfg(img)
    ienv = set(icfg.get("Env") or [])

    parts = ["docker run -d", "--name " + q(name)]

    # 只在容器层额外注入的 env（镜像自带的不用重复写）
    for e in cfg.get("Env") or []:
        if e not in ienv:
            parts.append("-e " + q(e))

    if hc.get("Privileged"):
        parts.append("--privileged")
    for cap in hc.get("CapAdd") or []:
        parts.append("--cap-add " + q(cap))
    for so in hc.get("SecurityOpt") or []:
        parts.append("--security-opt " + q(so))
    if hc.get("IpcMode") not in (None, "", "default"):
        parts.append("--ipc " + q(hc["IpcMode"]))
    if hc.get("PidMode") not in (None, "", "default"):
        parts.append("--pid " + q(hc["PidMode"]))
    if hc.get("ShmSize"):
        parts.append("--shm-size " + str(hc["ShmSize"]))
    if hc.get("NetworkMode") not in (None, "", "default"):
        parts.append("--network " + q(hc["NetworkMode"]))
    rp = hc.get("RestartPolicy") or {}
    if rp.get("Name") not in (None, "", "no"):
        suffix = ":%d" % (rp.get("MaximumRetryCount") or 0) if rp["Name"] == "on-failure" else ""
        parts.append("--restart " + rp["Name"] + suffix)
    if cfg.get("User"):
        parts.append("-u " + q(cfg["User"]))
    if cfg.get("WorkingDir"):
        parts.append("-w " + q(cfg["WorkingDir"]))

    # 挂载：HostConfig.Binds + Mounts（volume / 未被 Binds 覆盖的 bind）
    binds = list(hc.get("Binds") or [])
    for m in hc.get("Mounts") or []:
        if m.get("Type") == "volume":
            binds.append("%s:%s" % (m["Name"], m["Destination"]))
        elif m.get("Type") == "bind":
            pair = "%s:%s" % (m["Source"], m["Destination"])
            if not any(pair in b for b in binds):
                binds.append(pair)
    for b in binds:
        parts.append("-v " + q(b))

    # 设备（昇腾 NPU 的关键）
    for d in hc.get("Devices") or []:
        if d["PathOnHost"] == d["PathInContainer"]:
            parts.append("--device " + q(d["PathOnHost"]))
        else:
            parts.append("--device " + q(d["PathOnHost"] + ":" + d["PathInContainer"]))

    # 端口
    for cport, bindings in (hc.get("PortBindings") or {}).items():
        for b in bindings or []:
            hip = (b.get("HostIp") or "").replace("0.0.0.0", "")
            hp = b.get("HostPort") or ""
            parts.append("-p " + q((hip + ":" if hip else "") + (hp + ":" if hp else "") + cport))

    # entrypoint / cmd（只在与镜像不同时才写 entrypoint）
    ep = cfg.get("Entrypoint") or []
    if ep and ep != (icfg.get("Entrypoint") or []):
        parts.append("--entrypoint " + q(" ".join(ep)))

    parts.append(q(img))
    parts.extend(q(x) for x in (cfg.get("Cmd") or []))

    # 一行太长，按逻辑块折行
    lines = ["#!/usr/bin/env bash",
             "# auto-generated by generate-run-scripts.py",
             "# container : %s" % name,
             "# image     : %s" % img,
             "# created   : %s" % (c.get("Created") or ""),
             "# NOTE: 执行前必须先停掉/删掉同名容器，端口与设备不能冲突",
             ""]
    body = " \\\n  ".join(parts)
    lines.append(body)
    lines.append("")
    return "\n".join(lines)


def main():
    names = sys.argv[1:]
    if not names:
        names = sh(["docker", "ps", "-a", "--format", "{{.Names}}"]).split()
    os.makedirs(OUT_DIR, exist_ok=True)
    for n in names:
        try:
            content = build_run(n)
        except subprocess.CalledProcessError as exc:
            print("skip %s: %s" % (n, exc.stderr.strip()))
            continue
        path = os.path.join(OUT_DIR, "run-%s.sh" % n)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(content)
        os.chmod(path, 0o755)
        print("wrote %s" % path)


if __name__ == "__main__":
    main()
